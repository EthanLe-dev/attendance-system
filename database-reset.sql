DROP DATABASE IF EXISTS attendance_system;

CREATE DATABASE attendance_system
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE attendance_system;

CREATE TABLE student (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mssv VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    group_number INT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_student_mssv UNIQUE (mssv)
) ENGINE = InnoDB;

CREATE TABLE attendance_session (
    id BIGINT NOT NULL AUTO_INCREMENT,
    status VARCHAR(20) NOT NULL,
    opened_at DATETIME NULL,
    closed_at DATETIME NULL,
    PRIMARY KEY (id)
) ENGINE = InnoDB;

CREATE TABLE attendance (
    id BIGINT NOT NULL AUTO_INCREMENT,
    student_id BIGINT NOT NULL,
    checked_in_at DATETIME NOT NULL,
    latitude DECIMAL(10, 7) NULL,
    longitude DECIMAL(10, 7) NULL,
    accuracy DECIMAL(10, 2) NULL,
    selfie_path VARCHAR(500) NULL,
    gps_bypassed BOOLEAN NOT NULL DEFAULT FALSE,
    is_manual BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    CONSTRAINT uk_attendance_student UNIQUE (student_id),
    CONSTRAINT fk_attendance_student
        FOREIGN KEY (student_id) REFERENCES student(id)
) ENGINE = InnoDB;

